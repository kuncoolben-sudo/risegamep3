"""The island under the map, its sky and the props scattered over it, built procedurally (see world/*.py):

    public/models/w_terrain.glb  the ground (one vertex-coloured mesh) and the hand-placed things on it
    public/models/w_sky.glb      sky dome, clouds and sun at unit radius (the game scales it round the camera)
    public/models/w_props.glb    trees, palms, bushes, grass, flowers and rocks the game scatters (a root per kind)
    src/world3d/terrainData.ts   sea level, the obstacles the player walks round, and the trees/rocks on the slopes

Inside Blender (Scripting tab, or the MCP) it builds them in a 'World' collection and exports them. Headless:

    blender -b --python tools/blender/build_world.py -- [output_dir]
    python tools/blender/build_world.py [output_dir]

Set the globals ONLY (some of 'terrain', 'sky', 'props') and EXPORT (bool) before exec'ing this file to build a subset
or to skip writing files. The GLBs are Draco-compressed (decoded with public/draco/).
"""
import importlib
import json
import os
import sys

import bpy

# exec'd without __file__ (e.g. from the Blender MCP) it falls back to the repo's usual location
HERE = os.path.dirname(os.path.abspath(__file__)) if '__file__' in globals() else r'F:\risewebgame\p3\tools\blender'
_argv = [a for a in (sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]) if os.path.isdir(a)]
OUT = os.path.abspath(globals().get('OUT_DIR') or (_argv[0] if _argv else os.path.join(HERE, '../../public/models')))
DATA = os.path.abspath(os.path.join(HERE, '../../src/world3d/terrainData.ts'))
ONLY = globals().get('ONLY') or ('terrain', 'sky', 'props')
EXPORT = globals().get('EXPORT', True)
SKY_PREVIEW = 260  # the sky is shown this big round the island in Blender, and written at radius 1

sys.path.insert(0, HERE)
for _n in [n for n in sys.modules if n.split('.')[0] in ('pets', 'places', 'world')]:
    del sys.modules[_n]  # re-exec in a live Blender session must see edited modules
kit = importlib.import_module('pets.kit')
layout = importlib.import_module('world.layout')
ground = importlib.import_module('world.ground')
pieces = importlib.import_module('world.pieces')
props = importlib.import_module('world.props')
sky = importlib.import_module('world.sky')


def export(objs, path, roots=()):
    """Write exactly these objects as a Draco-compressed GLB; roots sit at the origin while it is written."""
    for o in bpy.context.view_layer.objects:  # select_all skips hidden objects, which would then be exported too
        try:
            o.select_set(False)
        except RuntimeError:
            pass
    saved = [(r, r.location.copy()) for r in roots]
    for r in roots:
        r.location = (0, 0, 0)
    bpy.context.view_layer.update()
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    try:
        bpy.ops.export_scene.gltf(filepath=path, export_format='GLB', use_selection=True, export_apply=True, export_yup=True,
                                  export_materials='EXPORT', export_cameras=False, export_lights=False, export_texcoords=False,
                                  export_animations=False, export_vertex_color='ACTIVE', export_draco_mesh_compression_enable=True)
    finally:
        for r, loc in saved:
            r.location = loc
    return f'{os.path.basename(path)}: {os.path.getsize(path) / 1024:.0f} KB'


def write_data(decor):
    obstacles = layout.obstacles()
    lines = ['// Generated by tools/blender/build_world.py from tools/blender/world/layout.py; do not edit by hand.',
             '// Three.js coordinates (x east, z south, y up) in world units.', '',
             f'export const SEA_LEVEL = {layout.SEA};',
             f'export const GRASS_RADIUS = {layout.GRASS_R};', '',
             '/** Circles [x, z, radius] the player walks round: mountains and hills, the lake, the waterfall, the beach pavilion. */',
             'export const OBSTACLES: [number, number, number][] = [']
    lines += [f'  [{x}, {z}, {r}],' for x, z, r in obstacles]
    lines += ['];', '', '/** Trees, palms and rocks on the slopes, beaches and islets: [kind, x, y, z, scale, turn]. */',
              'export const DECOR: [string, number, number, number, number, number][] = [']
    lines += [f'  {json.dumps(d)},' for d in decor]
    lines += ['];', '']
    with open(DATA, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    return f'terrainData.ts: {len(obstacles)} obstacles, {len(decor)} decor'


def main():
    if bpy.context.object and bpy.context.object.mode != 'OBJECT':
        bpy.ops.object.mode_set(mode='OBJECT')
    coll = bpy.data.collections.get('World') or bpy.data.collections.new('World')
    if coll.name not in bpy.context.scene.collection.children:
        bpy.context.scene.collection.children.link(coll)
    for o in list(coll.objects):  # rebuild cleanly on re-run
        bpy.data.objects.remove(o, do_unlink=True)
    for datablocks in (bpy.data.meshes, bpy.data.materials):
        for d in [d for d in datablocks if d.users == 0]:
            datablocks.remove(d)
    os.makedirs(OUT, exist_ok=True)
    report = []
    if 'terrain' in ONLY:
        g, n = ground.build(coll)
        p = kit.Pet('world', pieces.PALETTE, coll, 1.0)
        pieces.build(p)
        p.finish()
        decor = layout.decor(pieces.keep_out())
        report.append(f'ground: {n} faces, decor: {len(decor)}')
        if EXPORT:
            report.append(export([g] + p.objs, os.path.join(OUT, 'w_terrain.glb')))
            report.append(write_data(decor))
    if 'props' in ONLY:
        objs, roots = [], []
        for i, kind in enumerate(props.KINDS):
            q = kit.Pet(kind, props.PALETTE, coll, 1.0)
            props.build(kind, q)
            q.finish()
            q.root.location = (-30 + i * 6, -75, 0)  # in a row off the south coast, to look at
            objs += q.objs
            roots.append(q.root)
        if EXPORT:
            for r in roots:  # the game finds each kind by its root's name
                r.name = r['node']
            try:
                report.append(export(objs, os.path.join(OUT, 'w_props.glb'), roots))
            finally:
                for r in roots:
                    r.name = f"{r['node']}|{r['node']}"
    if 'sky' in ONLY:
        objs = sky.build(coll)
        if EXPORT:
            report.append(export(objs, os.path.join(OUT, 'w_sky.glb')))
        for o in objs:
            o.scale = (SKY_PREVIEW,) * 3
    for line in report:
        print(line)


main()
